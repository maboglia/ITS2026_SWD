package tipi;

public class Interi {

	public static void main(String[] args) {

		// Tipi interi
		byte mioByte = 127;
		System.out.println(mioByte);

		short mioShort = 851;
		System.out.println(mioShort);

		int intero = 1502;
		System.out.println(intero);
		
		long mioLong = 34093L;
		System.out.println(mioLong);
		
		
		

	}

}
