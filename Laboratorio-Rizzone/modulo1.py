def addizione(numero1, numero2):
    return numero1 + numero2

def sottrazione(numero1, numero2):
    return numero1 - numero2



def main():
    print("Benvenuto nel programma di calcolo!")
    print("Risultato dell'addizione:", addizione(5, 3))
    print("Risultato della sottrazione:", sottrazione(5, 3))

if __name__ == "__main__":
    main()